"""3. Dataset Profiler Function"""

def dataset_profiler(X, y):

    # Dataset size
    n_instances = X.shape[0]
    n_features = X.shape[1]

    # Feature types
    numerical_features = X.select_dtypes(
        include=np.number
    ).columns.tolist()

    categorical_features = X.select_dtypes(
        exclude=np.number
    ).columns.tolist()

    # Binary features
    binary_features = [
        col for col in X.columns
        if X[col].nunique(dropna=True) == 2
    ]

    # Target classes
    n_classes = y.nunique()

    # Class distribution
    class_distribution = y.value_counts().to_dict()

    # Imbalance ratio
    class_counts = y.value_counts()

    largest_class = class_counts.max()
    smallest_class = class_counts.min()

    imbalance_ratio = (
        largest_class / smallest_class
    )

    # Missing values
    total_missing = X.isnull().sum().sum()

    missing_percentage = (
        total_missing / X.size
    ) * 100

    # Duplicate records
    duplicate_records = X.duplicated().sum()

    # Feature-to-sample ratio
    feature_sample_ratio = (
        n_features / n_instances
    )

    # Statistics
    statistics = X.describe(
        include="all"
    )

    # Correlation
    correlation = X.corr(
        numeric_only=True
    )

    # Strong correlations
    strong_correlations = []

    if not correlation.empty:

        for i in range(len(correlation.columns)):

            for j in range(i + 1, len(correlation.columns)):

                value = correlation.iloc[i, j]

                if abs(value) >= 0.7:

                    strong_correlations.append(
                        (
                            correlation.columns[i],
                            correlation.columns[j],
                            value
                        )
                    )

    # Create profile
    profile = {

        "instances": n_instances,

        "features": n_features,

        "numerical_features":
            len(numerical_features),

        "categorical_features":
            len(categorical_features),

        "binary_features":
            len(binary_features),

        "classes":
            n_classes,

        "class_distribution":
            class_distribution,

        "imbalance_ratio":
            imbalance_ratio,

        "missing_values":
            total_missing,

        "missing_percentage":
            missing_percentage,

        "duplicate_records":
            duplicate_records,

        "feature_sample_ratio":
            feature_sample_ratio,

        "numerical_feature_names":
            numerical_features,

        "categorical_feature_names":
            categorical_features,

        "binary_feature_names":
            binary_features,

        "statistics":
            statistics,

        "correlation":
            correlation,

        "strong_correlations":
            strong_correlations
    }

    return profile

"""4. Automated Preprocessing"""

def automated_preprocessing(X, y, profile):

    X = X.copy()
    y = y.copy()

    decisions = []

    # --------------------------------
    # Handle duplicate records
    # --------------------------------

    duplicate_count = X.duplicated().sum()

    if duplicate_count > 0:

        duplicate_mask = X.duplicated()

        X = X.loc[~duplicate_mask].reset_index(drop=True)
        y = y.loc[~duplicate_mask].reset_index(drop=True)

        decisions.append(
            f"Removed {duplicate_count} duplicate records."
        )

    else:

        decisions.append(
            "No duplicate records found."
        )

    # --------------------------------
    # Identify feature types
    # --------------------------------

    numerical_features = X.select_dtypes(
        include=np.number
    ).columns.tolist()

    categorical_features = X.select_dtypes(
        exclude=np.number
    ).columns.tolist()

    # --------------------------------
    # Numerical pipeline WITHOUT scaling
    # --------------------------------

    numerical_pipeline_tree = Pipeline(
        steps=[
            (
                "imputer",
                SimpleImputer(strategy="median")
            )
        ]
    )

    # --------------------------------
    # Numerical pipeline WITH scaling
    # --------------------------------

    numerical_pipeline_scaled = Pipeline(
        steps=[
            (
                "imputer",
                SimpleImputer(strategy="median")
            ),

            (
                "scaler",
                StandardScaler()
            )
        ]
    )

    # --------------------------------
    # Categorical pipeline
    # --------------------------------

    categorical_pipeline = Pipeline(
        steps=[
            (
                "imputer",
                SimpleImputer(
                    strategy="most_frequent"
                )
            ),

            (
                "encoder",
                OneHotEncoder(
                    handle_unknown="ignore",
                    sparse_output=False
                )
            )
        ]
    )

    # --------------------------------
    # Tree preprocessor
    # --------------------------------

    tree_preprocessor = ColumnTransformer(
        transformers=[
            (
                "numerical",
                numerical_pipeline_tree,
                numerical_features
            ),

            (
                "categorical",
                categorical_pipeline,
                categorical_features
            )
        ]
    )

    # --------------------------------
    # Scaled preprocessor
    # --------------------------------

    scaled_preprocessor = ColumnTransformer(
        transformers=[
            (
                "numerical",
                numerical_pipeline_scaled,
                numerical_features
            ),

            (
                "categorical",
                categorical_pipeline,
                categorical_features
            )
        ]
    )

    # --------------------------------
    # Document decisions
    # --------------------------------

    if profile["missing_values"] > 0:

        decisions.append(
            "Missing values detected. "
            "Median imputation is used for numerical "
            "features and most-frequent imputation "
            "for categorical features."
        )

    else:

        decisions.append(
            "No missing values found."
        )

    if len(categorical_features) > 0:

        decisions.append(
            "Categorical features detected. "
            "One-Hot Encoding will be applied."
        )

    else:

        decisions.append(
            "No categorical features found."
        )

    decisions.append(
        "Feature scaling will be used for SVM and "
        "Naive Bayes pipelines."
    )

    decisions.append(
        "Feature scaling is not used for Decision Tree "
        "because tree-based models are not scale-sensitive."
    )

    return (
        X,
        y,
        tree_preprocessor,
        scaled_preprocessor,
        decisions
    )

"""5. Suitability Engine"""

def suitability_engine(profile):

    scores = {
        "Decision Tree": 0,
        "Naive Bayes": 0,
        "SVM": 0
    }

    reasons = {
        "Decision Tree": [],
        "Naive Bayes": [],
        "SVM": []
    }

    n = profile["instances"]
    p = profile["features"]

    # --------------------------------
    # Dataset size
    # --------------------------------

    if n < 1000:

        scores["Naive Bayes"] += 3

        reasons["Naive Bayes"].append(
            "The dataset is relatively small, "
            "which is suitable for Naive Bayes."
        )

        scores["SVM"] += 2

        reasons["SVM"].append(
            "SVM performs well on small and "
            "medium-sized datasets."
        )

        scores["Decision Tree"] += 2

        reasons["Decision Tree"].append(
            "Decision Tree works well on small "
            "and medium-sized datasets."
        )

    # --------------------------------
    # Feature dimensionality
    # --------------------------------

    if p >= 20:

        scores["SVM"] += 4

        reasons["SVM"].append(
            "The dataset has relatively high "
            "feature dimensionality."
        )

        scores["Naive Bayes"] += 3

        reasons["Naive Bayes"].append(
            "Naive Bayes can work efficiently "
            "with multiple features."
        )

    # --------------------------------
    # Feature/sample ratio
    # --------------------------------

    ratio = profile["feature_sample_ratio"]

    if ratio > 0.1:

        scores["SVM"] += 3

        reasons["SVM"].append(
            "The feature-to-sample ratio is high, "
            "which favors SVM."
        )

        scores["Naive Bayes"] += 2

        reasons["Naive Bayes"].append(
            "Naive Bayes is computationally efficient "
            "for high-dimensional datasets."
        )

    # --------------------------------
    # Categorical features
    # --------------------------------

    if profile["categorical_features"] > 0:

        scores["Decision Tree"] += 2

        reasons["Decision Tree"].append(
            "Categorical features are present and "
            "can be handled after encoding."
        )

        scores["Naive Bayes"] += 2

        reasons["Naive Bayes"].append(
            "Naive Bayes can use encoded categorical "
            "features."
        )

    # --------------------------------
    # Strong correlations
    # --------------------------------

    if len(profile["strong_correlations"]) > 0:

        scores["SVM"] += 2

        reasons["SVM"].append(
            "Strong feature dependencies are present."
        )

    # --------------------------------
    # Class imbalance
    # --------------------------------

    if profile["imbalance_ratio"] > 2:

        scores["Decision Tree"] += 1

        reasons["Decision Tree"].append(
            "Class imbalance is present."
        )

        scores["SVM"] += 1

        reasons["SVM"].append(
            "SVM can be adapted to imbalanced data."
        )

    # --------------------------------
    # Low dimensionality
    # --------------------------------

    if p < 10:

        scores["Decision Tree"] += 2

        reasons["Decision Tree"].append(
            "The dataset has relatively few features."
        )

    # --------------------------------
    # Prediction
    # --------------------------------

    predicted_algorithm = max(
        scores,
        key=scores.get
    )

    return scores, reasons, predicted_algorithm

"""6. Model Evaluation"""

def evaluate_model(
    name,
    model,
    X_train,
    X_test,
    y_train,
    y_test,
    X,
    y
):

    # Training time
    start = time.perf_counter()

    model.fit(
        X_train,
        y_train
    )

    training_time = (
        time.perf_counter() - start
    )

    # Prediction time
    start = time.perf_counter()

    predictions = model.predict(
        X_test
    )

    prediction_time = (
        time.perf_counter() - start
    )

    # Metrics
    accuracy = accuracy_score(
        y_test,
        predictions
    )

    precision = precision_score(
        y_test,
        predictions,
        average="weighted",
        zero_division=0
    )

    recall = recall_score(
        y_test,
        predictions,
        average="weighted",
        zero_division=0
    )

    f1 = f1_score(
        y_test,
        predictions,
        average="weighted",
        zero_division=0
    )

    # Confusion matrix
    cm = confusion_matrix(
        y_test,
        predictions
    )

    # 5-fold CV
    cv = StratifiedKFold(
        n_splits=5,
        shuffle=True,
        random_state=42
    )

    cv_scores = cross_val_score(
        model,
        X,
        y,
        cv=cv,
        scoring="f1_weighted",
        n_jobs=-1
    )

    cv_mean = cv_scores.mean()

    return {

        "Algorithm": name,

        "Accuracy": accuracy,

        "Precision": precision,

        "Recall": recall,

        "F1 Score": f1,

        "CV F1 Mean": cv_mean,

        "Training Time": training_time,

        "Prediction Time": prediction_time,

        "Confusion Matrix": cm
    }

"""7. SVM Hyperparameter Experiment"""

def svm_hyperparameter_experiment(
    preprocessor,
    X_train,
    y_train
):

    svm_pipeline = Pipeline(
        steps=[
            (
                "preprocessor",
                preprocessor
            ),

            (
                "svm",
                SVC()
            )
        ]
    )

    param_grid = {

        "svm__kernel": [
            "linear",
            "rbf"
        ],

        "svm__C": [
            0.1,
            1,
            10
        ],

        "svm__gamma": [
            "scale",
            0.01,
            0.1
        ]
    }

    grid = GridSearchCV(
        svm_pipeline,
        param_grid,
        cv=5,
        scoring="f1_weighted",
        n_jobs=-1
    )

    grid.fit(
        X_train,
        y_train
    )

    return grid

